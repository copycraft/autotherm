/**
 * Builds redirects/old-site.htaccess: 301 redirects from the old WordPress
 * site (autotherm.hu) to the new site (hutoautok.hu).
 *
 *   node redirects/build-redirects.js [old-urls.txt]
 *
 * Optionally pass a text file of old URLs (one per line) to print where each
 * one would land. Every redirect adds ?from=old, which the new site uses to
 * show its one-time "we have a new website" notice.
 */
const fs = require("fs");
const path = require("path");

const NEW = "https://hutoautok.hu";
const LANGS = ["hu", "en", "de", "ro"];

/** Pages that exist on the new site, per language (slugs mirror the old site). */
const PAGES = {
  hu: ["kik-vagyunk", "termekeink", "szerviz", "rakterhuto-szerviz", "miert-mi", "kepgaleria", "kapcsolat", "arajanlatkeres", "hutoauto-blog", "haszonjarmu-felepitmenyek", "jarmufelepitmeny-javitas", "szervizunk", "altalanos-szerzodesi-feltetelek", "adatkezelesi-tajekoztato", "ginop-palyazat"],
  en: ["who-are-we", "our-products", "why-us", "galeries", "contact", "quotation", "hutoautoblog", "commercial-vehicle-bodies", "van-isolations", "deceased-transport", "cooled-refrigerated-vehicle-bodies"],
  de: ["wer-sind-wir-3", "kuehlfahrzeug", "warum-gerade-wir", "aufbauten-galerie", "kontakt", "anfrage", "hutoauto-blog-2"],
  ro: ["cine-suntem-noi", "carosari-furgoane-frigorifice", "galerie-foto", "contact-2", "cerere-oferta", "blog"],
};

/** Landing pages used for old content that has no 1:1 page any more. */
const HOME = (l) => `/${l}`;
const GALLERY = { hu: "/hu/kepgaleria", en: "/en/galeries", de: "/de/aufbauten-galerie", ro: "/ro/galerie-foto" };
const PRODUCTS = { hu: "/hu/termekeink", en: "/en/our-products", de: "/de/kuehlfahrzeug", ro: "/ro/carosari-furgoane-frigorifice" };
const SERVICE = { hu: "/hu/szerviz", en: "/en/our-products", de: "/de/kuehlfahrzeug", ro: "/ro/carosari-furgoane-frigorifice" };
const BLOG = { hu: "/hu/hutoauto-blog", en: "/en/hutoautoblog", de: "/de/hutoauto-blog-2", ro: "/ro/blog" };
const QUOTE = { hu: "/hu/arajanlatkeres", en: "/en/quotation", de: "/de/anfrage", ro: "/ro/cerere-oferta" };

/** Ordered category rules for old URLs without a 1:1 match. First match wins. */
const CATEGORIES = [
  { name: "thank-you / campaign pages -> home", re: "(hutoauto$|koszonjuk|danke|dande|thank-you|multumesc|multumim|blackfriday|black_friday|jofogas|27-evesek|sikeres-igenyles|proba-csali|ebook|hentesek|cukraszatok|language|allaslehetoseg|munkatars|koronavirus)", to: HOME },
  { name: "galleries / 3D / portfolio -> gallery", re: "(3d|galeri|gallery|galerie|portfolio|kepgaleria|foto|umbauten|hutos-atalakitasok|husos-hutoauto-kepek)", to: (l) => GALLERY[l] },
  { name: "service -> service", re: "(servi|szerviz)", to: (l) => SERVICE[l] },
  { name: "vehicles / bodies -> products", re: "(felepitmeny|aufbauten|suprastructuri|carosa|kuehl|kuhl|vans?(-|$)|vehicle|35-ton|3-5-ton|furgon|autoutilitare|dube|nutzwagen|bestattungswagen|transport-funerar|frigorific|elektro|halottszallito)", to: (l) => PRODUCTS[l] },
  { name: "everything else (articles) -> blog", re: ".+", to: (l) => BLOG[l] },
];

const esc = (s) => s.replace(/[.+?^${}()|[\]\\]/g, "\\$&");
const dest = (p) => `${NEW}${p}?from=old`;

function classify(oldPath) {
  const p = oldPath.replace(/^\/|\/$/g, "");
  if (p === "") return { to: HOME("hu"), why: "root" };
  const m = p.match(/^(hu|en|de|ro)(?:\/(.*))?$/);
  const lang = m ? m[1] : "hu";
  const rest = m ? m[2] ?? "" : p;
  if (rest === "") return { to: HOME(lang), why: "language home" };
  const slug = rest.split("/").pop();
  if (rest.indexOf("/") === -1 && PAGES[lang].includes(rest)) return { to: `/${lang}/${rest}`, why: "1:1" };
  for (const c of CATEGORIES) {
    if (new RegExp(c.re, "i").test(rest)) return { to: c.to(lang), why: c.name };
  }
  return { to: BLOG[lang], why: "fallback" };
}

/* ------------------------------ .htaccess output ----------------------------- */

const out = [];
out.push("# 301 redirects from the old site to https://hutoautok.hu");
out.push("# Paste ABOVE the '# BEGIN WordPress' block in the old site's .htaccess.");
out.push("# Generated by redirects/build-redirects.js - do not edit by hand.");
out.push("<IfModule mod_rewrite.c>");
out.push("RewriteEngine On");
out.push("");
out.push("# Only the old domain (autotherm.hu and www.autotherm.hu)");
out.push("RewriteCond %{HTTP_HOST} ^(www\\.)?autotherm\\.hu$ [NC]");
out.push("RewriteRule ^$ " + dest(HOME("hu")) + " [R=301,L,QSD]");
out.push("");

out.push("# 1:1 pages (same address on the new site)");
for (const l of LANGS) {
  out.push("RewriteCond %{HTTP_HOST} ^(www\\.)?autotherm\\.hu$ [NC]");
  out.push(`RewriteRule ^${l}/(${PAGES[l].map(esc).join("|")})/?$ ${NEW}/${l}/$1?from=old [R=301,L,QSD]`);
}
out.push("");
out.push("# Language home pages");
out.push("RewriteCond %{HTTP_HOST} ^(www\\.)?autotherm\\.hu$ [NC]");
out.push(`RewriteRule ^(hu|en|de|ro)/?$ ${NEW}/$1?from=old [R=301,L,QSD]`);
out.push("");

// Category rules, one per language so the destination is correct.
for (const c of CATEGORIES) {
  out.push(`# ${c.name}`);
  for (const l of LANGS) {
    out.push("RewriteCond %{HTTP_HOST} ^(www\\.)?autotherm\\.hu$ [NC]");
    out.push(`RewriteRule ^${l}/${c.re === ".+" ? ".+" : `.*${c.re}.*`}$ ${dest(c.to(l))} [R=301,L,QSD,NC]`);
  }
  out.push("");
}
out.push("# Un-prefixed old paths (e.g. /portfolio/..., /hutos-atalakitasok/) -> gallery / home");
out.push("RewriteCond %{HTTP_HOST} ^(www\\.)?autotherm\\.hu$ [NC]");
out.push(`RewriteRule ^(portfolio|hutos-atalakitasok|husos-hutoauto-kepek|galeria-.*)(/.*)?$ ${dest(GALLERY.hu)} [R=301,L,QSD,NC]`);
out.push("RewriteCond %{HTTP_HOST} ^(www\\.)?autotherm\\.hu$ [NC]");
out.push(`RewriteRule ^koszonjuk-ajanlatkereset/?$ ${dest(HOME("hu"))} [R=301,L,QSD]`);
out.push("</IfModule>");

fs.writeFileSync(path.join(__dirname, "old-site.htaccess"), out.join("\n") + "\n");
console.log("wrote redirects/old-site.htaccess");

/* ------------------------------ simulation report ---------------------------- */

const file = process.argv[2];
if (file) {
  const urls = fs.readFileSync(file, "utf8").split(/\r?\n/).filter(Boolean);
  const counts = {};
  for (const u of urls) {
    const p = u.replace(/^https?:\/\/[^/]+/, "");
    const { to, why } = classify(p);
    counts[why] = (counts[why] ?? 0) + 1;
    if (process.argv.includes("--verbose")) console.log(`${p}  ->  ${to}  [${why}]`);
  }
  console.log(counts);
}
